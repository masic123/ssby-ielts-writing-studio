const normalize=(s:string)=>s.toLowerCase().replace(/writing task [12]|you should spend about \d+ minutes on this task\.?|write about the following topic:?|give reasons for your answer[\s\S]*|write (?:at least|no fewer than) \d+ words[\s\S]*/g,' ').replace(/[^a-z0-9]+/g,' ').trim();
function sameQuestion(a:string,b:string){
 if(a===b)return true;
 const x=new Set(a.split(' ').filter(t=>t.length>2)),y=new Set(b.split(' ').filter(t=>t.length>2));
 let common=0;for(const t of x)if(y.has(t))common++;
 return Math.min(x.size,y.size)>=10&&common/Math.max(1,x.size+y.size-common)>=.82;
}
export function selectAuditedScoringSamples(q:Question,essay:string){
 const matches=scoringSamples.filter(s=>s.task===q.task&&s.examType===q.examType&&sameQuestion(normalize(s.question),normalize(q.stem)));
 const forbidden=new Set(matches.flatMap(s=>questionGroups.find(g=>g.includes(s.id))||[s.id]));
 const pool=scoringSamples.filter(s=>developmentIds.has(s.id)&&!forbidden.has(s.id));
 return selectScoringSamples({...q,category:''},essay,pool);
}
