export function officialWritingRubric(q: Pick<Question, "task" | "examType">) {
  return {
    ...writingRubricSource,
    description: "官方公开 Band Descriptors 的中文要点转述；冲突时以官方原版为准。",
    principles: [
      "每项分别判断：必须满足某档正面特征，同时检查限制该项得分的负面表现。四项可以不同，不能用整体印象复制四个分数。",
      "单篇任务四项等权。整场 Writing 成绩另结合 Task 1 与 Task 2，Task 2 权重是 Task 1 的两倍；本报告不估计整场成绩。",
      "先判断回答题目、展开、组织、词汇精确性和句法控制，再参照带分样本理解分数边界；不能给样本缺失的四项数值补标签。",
      "不按段落数、连接词个数、生僻词数量或长难句数量直接给分；关注表达的准确、自然、恰当和灵活。",
      "字数不足会影响任务覆盖与语言能力的展示；不要自行发明固定扣几分的公式，也不要将一个维度的问题变成总分上限。",
      "Band 0 适用于未作答等无可评估回应；低于约20词的回应可评估证据极少，应按官方量表的相关限制判断。",
    ],
    criteria: {
      taskResponse: {
        name: q.task === "Task 2" ? "Task Response (TR)" : "Task Achievement (TA)",
        bands: q.task === "Task 2" ? taskResponse : q.examType === "A" ? academicAchievement : generalAchievement,
      },
      ...commonCriteria,
    },
  };
}
